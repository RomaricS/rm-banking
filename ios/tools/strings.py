DYNAMIC_PREFIXES = ["method.", "tab.", "pay.", "period.", "plan.", "goal.funding.", "channel.", "widget.goalStatus.", "freq."]

def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def specifiers(s):
    return re.findall(r"%(?:ld|@|d)", s)

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    errors = []
    for k, (en, fr) in S.items():
        if specifiers(en) != specifiers(fr):
            errors.append(f"format mismatch in {k}: {specifiers(en)} vs {specifiers(fr)}")
    used = set()
    for d in ["App", "Widgets"]:
        for dirpath, _, files in os.walk(os.path.join(root, d)):
            for f in files:
                if f.endswith(".swift"):
                    src = open(os.path.join(dirpath, f), encoding="utf-8").read()
                    used |= set(re.findall(r'(?:\btr|W\.t)\("([^"\\]+)"', src))
    for k in sorted(used):
        if k not in S:
            errors.append(f"missing key: {k}")
    unused = [k for k in S if k not in used and not any(k.startswith(p) for p in DYNAMIC_PREFIXES)]
    if errors:
        print("\n".join(errors)); sys.exit(1)
    out = os.path.join(root, "Shared", "Localization")
    for i, lang in enumerate(["en", "fr"]):
        os.makedirs(os.path.join(out, f"{lang}.lproj"), exist_ok=True)
        with open(os.path.join(out, f"{lang}.lproj", "Localizable.strings"), "w", encoding="utf-8") as fh:
            fh.write("/* Generated by ios/tools/strings.py — edit the table there, not this file. */\n\n")
            for k in sorted(S):
                fh.write(f'"{k}" = "{escape(S[k][i])}";\n')
        with open(os.path.join(out, f"{lang}.lproj", "InfoPlist.strings"), "w", encoding="utf-8") as fh:
            for k, v in INFO_PLIST.items():
                fh.write(f'"{k}" = "{escape(v[i])}";\n')
    print(f"ok: {len(S)} keys, {len(used)} used statically, {len(unused)} only used dynamically or unused")

if __name__ == "__main__":
    main()
